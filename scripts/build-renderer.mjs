import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { build } from "esbuild";
const require = createRequire(import.meta.url);
// The daemon bundle is self-contained; there are no browser executables or asset paths at runtime.
const wasm = await readFile(require.resolve("@resvg/resvg-wasm/index_bg.wasm"));
const font = await readFile("server/assets/NotoSansJP-Regular.otf");
// resvg runs on a worker thread so that a slow SVG can be terminated. The
// worker is evaluated from this source because the plugin is a single bundle.
const {
  outputFiles: [worker],
} = await build({
  entryPoints: ["renderer/rasterize-worker.ts"],
  bundle: true,
  platform: "node",
  format: "cjs",
  write: false,
  logLevel: "warning",
});
await mkdir("server/generated", { recursive: true });
await writeFile(
  "server/generated/rasterizer.ts",
  `// Generated by scripts/build-renderer.mjs.\nexport const rasterizerWasm = ${JSON.stringify(wasm.toString("base64"))};\nexport const japaneseFont = ${JSON.stringify(font.toString("base64"))};\nexport const rasterizerWorker = ${JSON.stringify(worker.text)};\n`,
);
await rm("server/generated/graphics.ts", { force: true });

// MathJax reaches its default font through package.json "imports". Paseo's
// compiler rejects that once npm installs MathJax beside the plugin instead of
// inside it, so the plugin imports MathJax as one generated module (ADR 14).
const { metafile } = await build({
  entryPoints: ["renderer/math.ts"],
  outfile: "server/generated/math.js",
  bundle: true,
  platform: "node",
  format: "esm",
  metafile: true,
  logLevel: "warning",
  banner: { js: "// Generated by scripts/build-renderer.mjs from renderer/math.ts." },
});
await writeFile(
  "server/generated/math.d.ts",
  `// Generated by scripts/build-renderer.mjs from renderer/math.ts.\nimport type { MathInput } from "../../shared/media";\nexport declare function mathSvg(input: MathInput): string;\n`,
);

// The npm package redistributes the bundled code, so ship its license.
const bundled = new Set();
for (const input of Object.keys(metafile.inputs)) {
  const directory = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input)?.[1];
  if (directory) bundled.add(directory);
}
const packages = await Promise.all(
  [...bundled].sort().map(async (directory) => ({
    directory,
    ...JSON.parse(await readFile(`${directory}/package.json`, "utf8")),
  })),
);
const unexpected = packages.filter(({ license }) => license !== "Apache-2.0");
if (unexpected.length)
  throw new Error(
    `Add the license of ${unexpected.map(({ name }) => name).join(", ")} to the math bundle notice in scripts/build-renderer.mjs`,
  );
const mathjax = packages.find(({ name }) => name === "@mathjax/src");
const apache = await readFile(`${mathjax.directory}/LICENSE`, "utf8");
await writeFile(
  "server/generated/math.LICENSE.txt",
  [
    "server/generated/math.js bundles the following packages under the Apache License 2.0:",
    "",
    ...packages.map(
      ({ name, version, repository }) =>
        `- ${name} ${version} (${repository?.url ?? repository})`,
    ),
    "",
    apache,
  ].join("\n"),
);
